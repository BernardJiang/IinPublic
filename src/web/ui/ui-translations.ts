export type UiTranslationKey = keyof typeof CATALOG.en;

export function uiLanguageFromProfile(languages: string[] | undefined): UiLanguage {
  return String(languages?.[0] || 'en').toLowerCase() === 'zh' ? 'zh' : 'en';
}

export function uiText(language: UiLanguage, key: UiTranslationKey): string {
  return CATALOG[language][key];
}

export function languageOptionLabel(language: UiLanguage, code: string, fallback: string): string {
  if (language !== 'zh') return fallback;
  return ({
    en: '英语',
    zh: '中文',
    es: '西班牙语',
    fr: '法语',
    de: '德语',
    ja: '日语',
    ko: '韩语',
  } as Record<string, string>)[code] || fallback;
}
